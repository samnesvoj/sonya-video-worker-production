#!/usr/bin/env python3
"""
Split requirements/worker.lock.txt into three hash-pinned layer files so Docker builds (and Vast pulls) get SEPARATE layers:
  01-cuda-libs   nvidia-* (cuDNN, cuBLAS, ... ~ 3 GB, changes almost never)
  02-torch       torch, torchvision, triton            (changes only on a PyTorch upgrade)
  03-rest        everything else                       (changes most often)
Layers download in parallel and an unchanged big layer is reused from the host cache. `--check` (CI) proves the union equals the lock.
"""
import hashlib, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
def _arg(flag, default):
    return pathlib.Path(sys.argv[sys.argv.index(flag) + 1]) if flag in sys.argv else default


LOCK = _arg("--lock", ROOT / "requirements" / "worker.lock.txt")      # e.g. requirements/candidates/torch213-cu126.lock.txt
OUT = _arg("--out", ROOT / "requirements" / "split")
# nvidia-ml-py (NVML bindings, tiny, imported by ultralytics) is NOT a CUDA library layer: it stays in 03-rest.
GROUPS = [("01-cuda-libs", re.compile(r"^(nvidia-(?!ml-py)|cuda-)")), ("02-torch", re.compile(r"^(torch|torchvision|triton)$"))]


def blocks(text: str):
    cur = None
    for line in text.splitlines(keepends=True):
        if line.startswith(("#", "\n")) and cur is None:
            continue
        if line[0] not in " \t#" and "==" in line:
            if cur:
                yield cur
            cur = [line]
        elif cur is not None:
            cur.append(line)
    if cur:
        yield cur


def split():
    files = {name: [] for name, _ in GROUPS}
    files["03-rest"] = []
    for b in blocks(LOCK.read_text()):
        pkg = re.match(r"([A-Za-z0-9_.-]+)==", b[0]).group(1).lower()
        files[next((n for n, rx in GROUPS if rx.match(pkg)), "03-rest")].append("".join(b))
    return {n: f"# split of worker.lock.txt (sha256 {hashlib.sha256(LOCK.read_bytes()).hexdigest()[:16]}) - generated by tools/split_lock.py\n" + "".join(v) for n, v in files.items()}


if __name__ == "__main__":
    parts = split()
    if "--check" in sys.argv:
        ok = True
        want = {n: t for n, t in parts.items()}
        for n, t in want.items():
            f = OUT / f"{n}.lock.txt"
            if not f.exists() or f.read_text() != t:
                print(f"out of date: {f.name}"); ok = False
        names = lambda ts: sorted(re.findall(r"^([A-Za-z0-9_.-]+==\S+)", "".join(ts), re.M))
        if names(want.values()) != names([LOCK.read_text()]):
            print("union of split files != lock"); ok = False
        sys.exit(0 if ok else 1)
    OUT.mkdir(exist_ok=True)
    for n, t in parts.items():
        (OUT / f"{n}.lock.txt").write_text(t)
        print(n, t.count("--hash=") , "hashes,", len(re.findall(r"^[A-Za-z0-9_.-]+==", t, re.M)), "packages")
